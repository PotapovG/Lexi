# Original practice corpus aligned with topics in Ελληνικά Α΄ units 1–4 (through p. 56).
# Plural drills are an explicitly requested supplement: noun plurals appear in unit 8 (p. 94).
WORDS = []
PHRASES = []
PLURALS = []
SENTENCES = []

def add_words(unit, topic, lines):
    for line in lines.strip().splitlines():
        gr, ru = [s.strip() for s in line.split("|", 1)]
        WORDS.append({"id": "w%03d" % (len(WORDS)+1), "unit":unit, "topic":topic, "kind":"word", "gr":gr, "ru":ru})

def add_phrases(unit, topic, lines):
    for line in lines.strip().splitlines():
        gr, ru = [s.strip() for s in line.split("|", 1)]
        PHRASES.append({"id":"p%03d" % (len(PHRASES)+1), "unit":unit, "topic":topic, "kind":"phrase", "gr":gr, "ru":ru})

def add_plurals(topic, lines):
    for line in lines.strip().splitlines():
        sg, pl, ru = [s.strip() for s in line.split("|", 2)]
        PLURALS.append({"id":"n%03d" % (len(PLURALS)+1), "unit":0, "topic":topic, "kind":"plural", "sg":sg, "pl":pl, "ru":ru, "supplemental":True})

def add_sentences(unit, lines):
    for line in lines.strip().splitlines():
        gr, ru = [s.strip() for s in line.split("|", 1)]
        SENTENCES.append({"id":"s%03d" % (len(SENTENCES)+1), "unit":unit, "topic":"Предложения", "kind":"sentence", "gr":gr, "ru":ru})

