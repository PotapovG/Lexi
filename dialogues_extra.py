    assert 1<=len(gaps)<=3,(i,title)
    assert len(set(gaps))==len(gaps),(i,title)
    assert all(lines.count(line)==1 for line in lines),(i,title)
    assert sum(len(re.findall(r'\[\[(\d+)\]\]',line)) for line in lines)==len(gaps),(i,title)
    found=sorted(int(s) for line in lines for s in re.findall(r'\[\[(\d+)\]\]',line))
    assert found==list(range(len(gaps))),(i,title,found)
    chapter_range=next(x for x in CHAPTERS if x[0]==chapter)
    assert chapter_range[1]<=page<=chapter_range[2],(i,page,chapter_range)
    # Deterministic cross-context distractors, uniquely shuffled per dialogue.
    pool=[v for v in DISTRACTORS[chapter] if v not in gaps]
    rng=random.Random(f'greek-dialogue-100:{i}:{chapter}:{title}')
    rng.shuffle(pool)
    wrong=pool[:8-len(gaps)]
    assert len(wrong)==8-len(gaps),(i,chapter)
    bank=gaps+wrong
    rng.shuffle(bank)
    assert len(bank)==len(set(bank))==8,(i,bank)
    CARDS.append(dict(id=f'dlg{i:03}',kind='dialogue',chapter=chapter,unit=chapter,
                      page=page,topic=title,gr=' '.join(lines),en='',source='original',
                      curriculum='book',lines=lines,gaps=gaps,bank=bank))

