def _parse(text):
    records={}
    for line in text.strip().splitlines():
        key,*values=line.split('|')
        assert key and values and all(values)
        cid="dlg"+key if not key.startswith("dlg") else key
        assert cid not in records
        records[cid]=tuple(values)
    return records

